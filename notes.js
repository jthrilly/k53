<ul>
<li>Most testing centres now use the <b>computerised learner's licence test (CLLT)</b>: a touch-screen kiosk with fingerprint check, 64 questions drawn at random from a pool of about 1 200, marked instantly. It is available in 11 languages with an audio option and has a demo mode first.</li>
<li>Every question has <b>three options</b>. Some ask you to "select the correct combination" of statements (i), (ii), (iii).</li>
<li>Controls questions show a <b>numbered picture of a car's controls</b> (1 to 11). Learn the numbers – see Controls below.</li>
<li>Allow about an hour. Some older paper tests had 68 questions (30 signs, 30 rules, 8 controls) with the same pass marks.</li>
</ul>
