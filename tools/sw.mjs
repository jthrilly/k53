// Writes dist/sw.js: precaches every file in the build so the app works offline.
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';
const dist = new URL('../dist/', import.meta.url).pathname;
const files = [];
(function walk(d) { for (const f of readdirSync(d)) { const p = join(d, f); statSync(p).isDirectory() ? walk(p) : files.push(relative(dist, p)); } })(dist);
const list = ['./', ...files.filter(f => f !== 'sw.js')].sort();
const version = createHash('sha1').update(list.join('|') + files.map(f => statSync(join(dist, f)).size).join(',')).digest('hex').slice(0, 10);
writeFileSync(join(dist, 'sw.js'), `/* Generated by tools/sw.mjs */
const VERSION = 'k53-${version}';
const FILES = ${JSON.stringify(list)};
self.addEventListener('install', e => { e.waitUntil(caches.open(VERSION).then(c => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== VERSION).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then(hit => hit || fetch(e.request).catch(() => caches.match('./'))));
});
`);
console.log(`sw.js: ${list.length} files, version ${version}`);
